"""
Канал доставки «Вебхук» — заглушка с тем же протоколом (ТЗ 8.3, plan.md этап 5).

«POST с телом события на ваш адрес» — так вебхук описан в прототипе. Реализация отложена вместе
с почтой, протокол соблюдён.

В отличие от Telegram и почты, у вебхука нет **подключения**: секрета, который давал бы доступ
к чужой инфраструктуре, здесь нет — есть только адресат, то есть URL, и он задаётся в интерфейсе
(8.3). Поэтому канал считается настроенным всегда, а решает наличие адресата.

TODO(ТЗ 8.3): POST с телом события. Понадобится формат тела — сейчас в `send` приходит готовый
текст сообщения (8.4), а вебхуку разумнее отдавать структуру; это отдельное решение, и его
придётся согласовать, потому что новых терминов оно не вводит, но меняет контракт порта.
"""

from __future__ import annotations

from core.ports.notification_channel import NotificationChannel, NotSent, SendResult

NOT_IMPLEMENTED = (
    'канал «Вебхук» не реализован: в первой версии обязателен только Telegram (ТЗ 8.3)'
)


class WebhookChannel(NotificationChannel):
    @property
    def is_configured(self) -> bool:
        """Настраивать в окружении нечего: у вебхука есть только адресат, и он в интерфейсе."""
        return True

    def send(self, *, recipient: str, text: str, reply_to: str | None = None) -> SendResult:
        """
        Пока отказ, но штатный: он попадёт в журнал рядом с событием (8.3).

        `retryable=False`: реализация не появится от повтора, а пять попыток только оттянули бы
        запись в журнал.
        """
        if not recipient:
            return NotSent(error='адрес вебхука не задан', retryable=False)
        return NotSent(error=NOT_IMPLEMENTED, retryable=False)
