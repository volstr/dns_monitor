from __future__ import annotations

from core.ports.notification_channel import NotificationChannel, NotSent, SendResult

NOT_IMPLEMENTED = (
    "канал «Почта» не реализован: в первой версии обязателен только Telegram (ТЗ 8.3)"
)


class SmtpChannel(NotificationChannel):
    def __init__(self, host: str | None, sender: str | None = None) -> None:
        self._host = host
        self._sender = sender

    @property
    def is_configured(self) -> bool:
        """«Настроен» — это заданные адрес сервера и отправитель (11.10 проверяет их связку).

        Пустой `SMTP_HOST` — нормальный режим работы, а не ошибка конфигурации: без него
        приглашение письмом просто недоступно (критерий 75).
        """
        return bool(self._host and self._sender)

    def send(self, *, recipient: str, text: str, reply_to: str | None = None) -> SendResult:
        """Пока отказ, но штатный: он попадёт в журнал рядом с событием (8.3), а не уронит процесс.

        Повторять бессмысленно — реализация не появится от повтора, поэтому `retryable=False`.
        """
        return NotSent(error=NOT_IMPLEMENTED, retryable=False)
