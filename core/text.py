"""
Работа с текстом — ТЗ 8.4, 11.9.

Экранирование нужно и адаптеру канала, и составителю сообщения, поэтому живёт здесь: дублировать
его через границу слоёв значит однажды получить две разные версии.

По той же причине здесь же длительность. Она встречается в трёх местах — «Проблема держалась …»
(критерий 17), «Возраст: …» в напоминании (11.9) и период проверки в списке доменов (11.5), — и
до этого существовала двумя одинаковыми приватными копиями.
"""

from __future__ import annotations

from datetime import timedelta


def escape_html(text: str) -> str:
    """
    Экранирование для ограниченного HTML (8.4).

    Три символа вместо восемнадцати у MarkdownV2 — потому HTML и выбран: ошибка экранирования не
    превращает сообщение в кашу из служебных знаков.
    """
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def plural(count: int, one: str, few: str, many: str) -> str:
    """
    Русское согласование числительного: «1 запись», «2 записи», «5 записей».

    Нужно подписям списка доменов (11.5) и колонке «Проверка адресов». Своё, а не `pluralize`
    Django: штатный фильтр умеет только две формы и в русском даёт «5 записи».
    """
    tens = count % 100
    if 11 <= tens <= 14:
        return many
    match count % 10:
        case 1:
            return one
        case 2 | 3 | 4:
            return few
        case _:
            return many


def humanize_duration(delta: timedelta) -> str:
    """
    Длительность по-русски: «26 мин», «3 ч 12 мин».

    Формат взят из прототипа (блок 11.9 «держится 3 ч 12 мин») и сохранён дословно: он уже
    закреплён тестами критерия 17 и напоминаний. Секунды не показываются — ни одно из трёх мест
    не оперирует ими: минимальный период проверки по ТЗ и так минута.
    """
    minutes = int(delta.total_seconds()) // 60
    if minutes < 60:
        return f"{minutes} мин"
    return f"{minutes // 60} ч {minutes % 60} мин"
