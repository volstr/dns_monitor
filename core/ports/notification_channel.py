"""Порт канала доставки — ТЗ 8.3.

Требование 8.3: «Архитектуру каналов сделать расширяемой: почта и вебхук предусмотрены,
реализация почты может быть отложена». Поэтому канал — протокол, а не класс с наследниками:
Telegram, почта и вебхук реализуют один и тот же `send`.

**Подключение против адресата (8.3).** Порт получает готового адресата строкой. Всё, что даёт
доступ к чужой инфраструктуре — токен бота, учётные данные почтового сервера, — живёт в окружении
и до порта не доходит: администратор приложения не должен иметь возможности направить исходящее
через свой сервер.

Отказ — штатный исход и возвращается результатом, а не исключением (`CLAUDE.md`).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True, slots=True)
class Sent:
    """Доставлено. Идентификатор нужен, чтобы отвечать в ветку (7.3, 8.5)."""

    channel_message_id: str


@dataclass(frozen=True, slots=True)
class NotSent:
    error: str
    #: Имеет ли смысл повторять. Таймаут и «слишком много запросов» — да; «чат не найден» и
    #: «бот заблокирован» — нет, и пять повторов такого отказа только оттянут запись в журнал.
    retryable: bool = True


type SendResult = Sent | NotSent


class NotificationChannel(Protocol):
    def send(self, *, recipient: str, text: str, reply_to: str | None = None) -> SendResult:
        """Отправить готовый текст. Составление сообщения (8.4) остаётся снаружи.

        ``reply_to`` — идентификатор сообщения, в ветку которого отвечаем. Пусто означает
        самостоятельное сообщение: по правилу Q-D7 продолжение существует только при наличии
        открывающего сообщения.
        """
