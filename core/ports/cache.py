"""
Порт кэша — ТЗ 11.12.

Отдельно от ``StateStore`` намеренно, и это не дублирование. 11.12 требует **другой логической
базы** с другой политикой вытеснения: кэш можно сбросить целиком в любой момент, рабочее
состояние — нельзя. Один порт на оба вида данных стирал бы ровно ту границу, ради которой они и
разделены: достаточно однажды положить блокировку планировщика «в кэш», и критерий 62 перестаёт
выполняться, причём молча.

Ключ здесь, как и у состояния, несёт срок жизни в себе: ``CacheKey`` без ``ttl`` не
конструируется, поэтому «забыть TTL» нельзя даже синтаксически (11.11, `CLAUDE.md`).

**Два правила обновления, и путать их нельзя** (11.12):

- *по сроку* — представления: обзор, список доменов, график реестра. Отставание на секунды
  безвредно, а явная инвалидация каждого представления при каждом событии обошлась бы дороже
  пользы;
- *по версии в ключе* — настройки и белый список. Здесь отставание опасно: человек, добавивший
  подсеть, чтобы прекратить ложную тревогу, обязан увидеть результат на следующей же проверке.
  Версия предпочтительнее удаления ключа — при нескольких экземплярах сервиса удаление
  подвержено гонке, а смена версии просто делает старый ключ недостижимым, и он уходит по сроку.

Исключение из обоих правил одно: ``cache:user:{id}`` удаляется **немедленно** при смене роли или
отключении участника (11.12, критерий 61). Отозванный доступ не должен переживать своё отзывание.

Чего здесь нет и не появится (11.12, «не кэшируются никогда»): результат проверки вхождения
конкретного адреса, содержимое журнала событий, реестр адресов как таковой, данные
аутентификации.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import timedelta
from typing import Protocol

#: Общий префикс. Сброс по шаблону `cache:*` обязан быть безопасной операцией под нагрузкой
#: (11.12, критерий 62), а значит ничего, кроме кэша, под этот шаблон попадать не должно.
PREFIX = "cache:"

# Сроки из таблицы 11.12.
SETTINGS_TTL = timedelta(hours=1)
ALLOWLIST_TTL = timedelta(hours=1)
TRACE_TTL = timedelta(minutes=5)
OVERVIEW_TTL = timedelta(seconds=15)
DOMAIN_LIST_TTL = timedelta(seconds=30)
USER_TTL = timedelta(seconds=30)


@dataclass(frozen=True, slots=True)
class CacheKey:
    """Ключ вместе со сроком жизни. Одно без другого не существует (11.11, 11.12)."""

    name: str
    ttl: timedelta


def settings_of_domain(domain_id: int, version: int) -> CacheKey:
    """Разрешённые по цепочке наследования настройки домена. Обновление — по версии."""
    return CacheKey(f"{PREFIX}settings:domain:{domain_id}:v{version}", SETTINGS_TTL)


def allowlist_of_domain(domain_id: int, version: int) -> CacheKey:
    """Разобранный белый список в виде диапазонов. Обновление — по версии."""
    return CacheKey(f"{PREFIX}allowlist:domain:{domain_id}:v{version}", ALLOWLIST_TTL)


def trace_of_domain(domain_id: int, bucket_seconds: int) -> CacheKey:
    """След для графика реестра, агрегированный по корзинам (9.2). Обновление — по сроку."""
    return CacheKey(f"{PREFIX}trace:domain:{domain_id}:{bucket_seconds}", TRACE_TTL)


def overview_view() -> CacheKey:
    """Счётчики и открытые расхождения на обзоре (11.9). Обновление — по сроку."""
    return CacheKey(f"{PREFIX}view:overview", OVERVIEW_TTL)


def domain_list_view(filter_hash: str) -> CacheKey:
    """Страница списка доменов со статусами. Обновление — по сроку."""
    return CacheKey(f"{PREFIX}view:domains:{filter_hash}", DOMAIN_LIST_TTL)


def user(member_id: int) -> CacheKey:
    """Роль и признак активности участника. Удаляется немедленно при их изменении."""
    return CacheKey(f"{PREFIX}user:{member_id}", USER_TTL)


class Cache(Protocol):
    def get(self, key: CacheKey) -> str | None:
        """Прочитать. ``None`` — ключа нет, срок истёк или его вытеснили."""
        ...

    def put(self, key: CacheKey, value: str) -> None:
        """Записать вместе со сроком жизни."""
        ...

    def forget(self, key: CacheKey) -> None:
        """
        Удалить один ключ немедленно.

        Нужен ровно одному ключу — ``cache:user:{id}`` (11.12). Настройки и белый список
        обновляются сменой версии, а не удалением: при нескольких экземплярах сервиса удаление
        подвержено гонке.
        """
        ...

    def flush(self) -> int:
        """
        Сбросить всё пространство ``cache:*`` и вернуть число удалённых ключей.

        По 11.12 это безопасная операция под нагрузкой: рабочее состояние лежит в другой
        логической базе и не задевается (критерий 62).
        """
        ...
