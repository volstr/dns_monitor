"""Данные клиентских виджетов — ТЗ 9.2, 11.4; `CLAUDE.md`.

Клиентский код существует ровно в трёх местах, и два из них рисуют картинки по данным: линейка
подсети (11.4) и график следа реестра (9.2). Данные уходят рядом с элементом в
``<script type="application/json">``, поэтому описаны ``TypedDict`` — это тот самый случай,
который `CLAUDE.md` называет прямо: «словарные структуры, уходящие в JSON: данные виджетов».

**Позиции считает сервер, а не браузер.** Адрес IPv6 — это 128 бит, и в числе JavaScript он не
помещается: вычисленная на клиенте позиция врала бы тем сильнее, чем длиннее префикс. Поэтому
сюда уходит уже готовая доля от нуля до единицы.
"""

from __future__ import annotations

from typing import TypedDict


class RulerMark(TypedDict):
    """Отметка адреса на линейке подсети."""

    address: str
    #: Доля диапазона от 0 до 1. Считается на сервере: целочисленная арифметика там точная.
    position: float
    #: Класс состояния: matched / unmatched / stale / not_checked. Задаёт цвет отметки.
    status: str


class RulerData(TypedDict):
    """Одна линейка — одна запись белого списка с маской."""

    entry: str
    first: str
    middle: str
    last: str
    size: int
    marks: list[RulerMark]


class TraceRow(TypedDict):
    """След одного адреса: в какие сутки он отдавался."""

    address: str
    status: str
    #: Номера суток от начала наблюдения. Корзина закрашена, если адрес был хотя бы в одном
    #: ответе за эти сутки (9.2).
    days: list[int]


class TraceData(TypedDict):
    """След всего реестра домена."""

    #: Первые сутки наблюдения, ISO. Ось по умолчанию охватывает весь срок (9.2).
    start: str
    #: Сколько суток охватывает ось, считая начальные.
    days: int
    rows: list[TraceRow]
