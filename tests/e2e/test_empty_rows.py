"""
Строка «ничего нет» в списках-сетках — ТЗ 11.7, 11.8, 11.9; правка переноса 12.

Проверка браузерная, потому что проверяемое существует только после раскладки: `.hist` и
`.feed` — сетка из узкой колонки для времени и широкой для содержания. У строки «пусто» времени
нет, и её единственный элемент попадал в **узкую** колонку — текст выкладывался столбиком по
96 пикселей. В разметке при этом всё выглядело правильно, поэтому ни один серверный тест этого
не видел.

Утверждение намеренно грубое: «шире узкой колонки». Точная ширина зависит от шрифта и окна, и
закреплять её значило бы ломать тест при любой правке оформления. Поймать нужно другое —
возвращение текста в колонку времени.
"""

from typing import Any

import pytest

pytestmark = [pytest.mark.e2e, pytest.mark.django_db]

#: Ширина колонки времени у `.hist` (CSS). Текст, попавший в неё, этой ширины и будет.
TIME_COLUMN = 96


def test_11_9_empty_row_is_not_squeezed_into_the_time_column(
    signed_in: Any, live_server: Any
) -> None:
    """На свежей установке расхождений нет, и обзор показывает именно эту строку."""
    page = signed_in
    page.goto(f"{live_server.url}/")

    row = page.locator(".hist li.empty .sub")
    row.wait_for()
    width = row.evaluate("el => el.getBoundingClientRect().width")

    assert width > TIME_COLUMN * 2, f"текст шириной {width:.0f}px — он в колонке времени"
